package com.modocument.infrastructure.transform.code;

import java.util.ArrayList;
import java.util.List;
import java.util.regex.Pattern;

/**
 * Drops what is not data from a text table: blank rows, repeated header rows
 * (page breaks), markdown separator rows, total/subtotal rows, page footers
 * and trailing one-cell notes, and wholly empty unnamed columns.
 */
final class TableCleaner {

    private static final Pattern TOTAL_LABEL = Pattern.compile(
            "(?i)(grand\\s+|sub\\s*-?\\s*)?totals?\\b.*|sum\\b.*|"
                    + "balance\\s+(c/f|b/f|carried\\s+forward|brought\\s+forward)\\b.*");
    private static final Pattern FOOTER = Pattern.compile(
            "(?i)page\\s+\\d+(\\s*(of|/)\\s*\\d+)?|end\\s+of\\s+(report|statement|document|file)\\b.*"
                    + "|(generated|printed|produced)\\s+(on|by|at)\\b.*|\\(?continued( on next page)?\\)?\\.?"
                    + "|\\*+\\s*end\\b.*");
    private static final Pattern SEPARATOR_CELL = Pattern.compile("[-=:+_ ]{2,}");

    /** The cleaned table: unique headers and rows of the same width. */
    record Table(List<String> headers, List<List<String>> rows) {
    }

    private TableCleaner() {
    }

    static Table clean(List<String> headers, List<List<String>> rows, List<String> notes) {
        int width = headers.size();
        List<String> headerKeys = headers.stream().map(TextCells::key).toList();
        List<List<String>> kept = new ArrayList<>(rows.size());
        int blank = 0;
        int repeatedHeader = 0;
        int totals = 0;
        int footers = 0;
        for (List<String> raw : rows) {
            List<String> row = TextCells.fit(raw, width);
            int filled = TextCells.nonBlankCount(row);
            if (filled == 0 || isSeparatorRow(row)) {
                blank++;
                continue;
            }
            if (isRepeatedHeader(row, headerKeys)) {
                repeatedHeader++;
                continue;
            }
            if (isTotalRow(row)) {
                totals++;
                continue;
            }
            if (filled == 1 && FOOTER.matcher(firstNonBlank(row)).matches()) {
                footers++;
                continue;
            }
            kept.add(row);
        }
        // Trailing one-cell notes after the last real row ("Generated by …", "Thank you").
        if (width >= 3) {
            while (!kept.isEmpty() && TextCells.nonBlankCount(kept.get(kept.size() - 1)) <= 1
                    && kept.size() > 1) {
                kept.remove(kept.size() - 1);
                footers++;
            }
        }
        note(notes, blank, "blank or separator row");
        note(notes, repeatedHeader, "repeated header row");
        note(notes, totals, "total row");
        note(notes, footers, "footer row");
        return dropEmptyColumns(headers, kept, notes);
    }

    static boolean isTotalRow(List<String> row) {
        int checked = 0;
        boolean label = false;
        for (String cell : row) {
            if (TextCells.isBlank(cell)) {
                continue;
            }
            if (!label && checked < 2 && TOTAL_LABEL.matcher(cell).matches()) {
                label = true;
                checked++;
                continue;
            }
            checked++;
            if (TextCells.looksDate(cell)) {
                return false;
            }
            if (!TextCells.looksNumeric(cell) && label) {
                return false;
            }
        }
        return label;
    }

    private static boolean isRepeatedHeader(List<String> row, List<String> headerKeys) {
        int matches = 0;
        int filled = 0;
        for (int i = 0; i < row.size(); i++) {
            String key = TextCells.key(row.get(i));
            if (key.isEmpty()) {
                continue;
            }
            filled++;
            if (key.equals(headerKeys.get(i))) {
                matches++;
            }
        }
        return filled >= 2 && matches == filled;
    }

    private static boolean isSeparatorRow(List<String> row) {
        for (String cell : row) {
            if (!TextCells.isBlank(cell) && !SEPARATOR_CELL.matcher(cell).matches()) {
                return false;
            }
        }
        return true;
    }

    private static String firstNonBlank(List<String> row) {
        for (String cell : row) {
            if (!TextCells.isBlank(cell)) {
                return cell;
            }
        }
        return "";
    }

    private static Table dropEmptyColumns(List<String> headers, List<List<String>> rows, List<String> notes) {
        List<Integer> keep = new ArrayList<>();
        for (int c = 0; c < headers.size(); c++) {
            boolean generated = TextCells.isGeneratedHeader(headers.get(c));
            boolean anyValue = false;
            for (List<String> row : rows) {
                if (!row.get(c).isEmpty()) {
                    anyValue = true;
                    break;
                }
            }
            if (anyValue || !generated) {
                keep.add(c);
            }
        }
        if (keep.size() == headers.size()) {
            return new Table(headers, rows);
        }
        note(notes, headers.size() - keep.size(), "empty unnamed column");
        List<String> keptHeaders = keep.stream().map(headers::get).toList();
        List<List<String>> keptRows = new ArrayList<>(rows.size());
        for (List<String> row : rows) {
            keptRows.add(keep.stream().map(row::get).toList());
        }
        return new Table(keptHeaders, keptRows);
    }

    private static void note(List<String> notes, int count, String what) {
        if (count > 0) {
            notes.add("dropped " + count + " " + what + (count == 1 ? "" : "s"));
        }
    }
}
