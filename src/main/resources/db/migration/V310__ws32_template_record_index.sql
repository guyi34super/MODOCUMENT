-- Flow records in document creation (docs/doccreation/flow-records-contract.md
-- §1, ws32): the searchable index of validated records.
--
--  * TemplateRecord — one row per VALID row of a VALIDATED/EXPORTED ingestion
--    job (a MappedRowsJson row without an entry in ValidationResultJson).
--    RowIndex is the 1-based row of the job's mapped table. ValuesJson is the
--    row (template field name -> value); SearchText the values lower-cased,
--    accent-folded and joined with " ". OwnerUserId is the job's owner (the
--    visibility rule: own jobs, or any job on a BANK-shared template).
--    Written after the job's commit by TemplateRecordIndexer; a remap, row
--    edit or re-validation deletes and re-inserts the job's rows, deleting the
--    job deletes them (ON DELETE CASCADE backs the explicit delete), and the
--    retention purge and a DSR erase remove them.
--  * TemplateRecordKey — every non-blank field of every record, normalised
--    (trimmed, lower-cased, whitespace and punctuation removed, at most 256
--    characters), so any field can serve as the join key of a LINKED source.
--  * DocInstance.SourceRecordsJson — the records a document was filled from,
--    [{recordId, templateId, role}].
--
-- ROW LEVEL SECURITY: both tables carry BankId, so the afterMigrate callback
-- puts them under the tenant policy (RlsPolicyCoveragePgIT lists them).
--
-- EXPAND/CONTRACT (docs/release/migration-policy.md): new tables and a
-- nullable column only.
--
-- SCHEMA PARITY: the TemplateRecord / TemplateRecordKey entities mirror this
-- file on the H2 test schema (ddl-auto: create).

CREATE TABLE IF NOT EXISTS TemplateRecord (
    TemplateRecordId bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BankId           integer NOT NULL REFERENCES Bank (BankId),
    TemplateId       integer NOT NULL REFERENCES Template (TemplateId) ON DELETE CASCADE,
    IngestionJobId   integer NOT NULL REFERENCES IngestionJob (IngestionJobId) ON DELETE CASCADE,
    RowIndex         integer NOT NULL,
    OwnerUserId      integer NOT NULL,
    ValuesJson       text NOT NULL,
    SearchText       text NOT NULL,
    CreatedAt        timestamp NOT NULL,
    CONSTRAINT ux_templaterecord_job_row UNIQUE (IngestionJobId, RowIndex)
);

CREATE INDEX IF NOT EXISTS ix_templaterecord_bank_template_created
    ON TemplateRecord (BankId, TemplateId, CreatedAt DESC);

CREATE TABLE IF NOT EXISTS TemplateRecordKey (
    TemplateRecordId bigint NOT NULL REFERENCES TemplateRecord (TemplateRecordId) ON DELETE CASCADE,
    BankId           integer NOT NULL REFERENCES Bank (BankId),
    FieldName        varchar(255) NOT NULL,
    KeyValue         varchar(256) NOT NULL,
    CONSTRAINT pk_templaterecordkey PRIMARY KEY (TemplateRecordId, FieldName)
);

CREATE INDEX IF NOT EXISTS ix_templaterecordkey_bank_field_value
    ON TemplateRecordKey (BankId, FieldName, KeyValue);

ALTER TABLE DocInstance ADD COLUMN IF NOT EXISTS SourceRecordsJson text;
