-- ws29 (v1.2.0 optimization round — docs/optimization/contracts.md §7), BUG-12
-- (docs/qa/optimization-signoff.md): the retry queue of stored-object deletes.
--
-- The retention purge, the DSR erase and a job deletion delete their rows
-- first and the stored objects (disk or S3) after the commit
-- (AfterCommitFileDeleter). An object delete that still fails after the
-- short in-call retries used to be logged and dropped: nothing pointed at the
-- object any more, so customer data outlived its retention or erasure. Such a
-- key is now written here, and PendingFileDeleteSweeper retries it with
-- backoff until the store confirms the delete; the row is then removed.
-- A row is never dropped while its object may still exist.
--
--  * StorageKey — the FileStore key (uploads/…, exports/…), never content.
--  * Attempts / NextAttemptAt / LastError — retry bookkeeping: Attempts counts
--    the sweeper's failed retries (a new row is due at once, then 5 minutes
--    doubling to 6 hours); LastError is the store's error class and message,
--    truncated.
--  * One row per (BankId, StorageKey): queuing the same key twice is a no-op.
--
-- ROW LEVEL SECURITY: the table carries BankId, so the afterMigrate callback
-- puts it under the tenant policy; RlsPolicyCoveragePgIT's inventory lists
-- 'pendingfiledelete'. The sweeper lists the banks with due rows as SYSTEM
-- (ids only) and retries each bank's rows under runAs(bank).
--
-- EXPAND/CONTRACT (docs/release/migration-policy.md): a new table only; the
-- previous release never reads it.
--
-- SCHEMA PARITY: the PendingFileDelete entity mirrors this file on the H2
-- test schema (ddl-auto: create).

CREATE TABLE IF NOT EXISTS PendingFileDelete (
    PendingFileDeleteId bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BankId              integer NOT NULL REFERENCES Bank (BankId),
    StorageKey          varchar(1024) NOT NULL,
    Attempts            integer NOT NULL DEFAULT 0,
    LastError           varchar(500),
    CreatedAt           timestamptz NOT NULL,
    NextAttemptAt       timestamptz NOT NULL,
    CONSTRAINT ux_pendingfiledelete_bank_key UNIQUE (BankId, StorageKey)
);

-- The sweep: one bank's rows that are due.
CREATE INDEX IF NOT EXISTS ix_pendingfiledelete_bankid_nextattemptat
    ON PendingFileDelete (BankId, NextAttemptAt);
