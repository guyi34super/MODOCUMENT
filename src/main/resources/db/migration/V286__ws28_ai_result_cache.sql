-- ws28 (v1.2.0 optimization round — docs/optimization/contracts.md §1), SE4:
-- the AI result cache. Re-uploading the same document against the same
-- template costs no tokens: the parse step looks the AI's parsed table up
-- here before calling the model and stores it after a successful AI parse.
--
--  * CacheKey — sha256 (64 hex) of: sha256(extracted document text),
--    template id + a hash of its field definitions (the template "version"),
--    the extraction mode and parsing options, the model and the prompt
--    version. One row per (BankId, CacheKey).
--  * PromptVersion / Model — stored for diagnostics and targeted purges; a
--    new prompt version or model simply produces new keys.
--  * ResultJson — the parsed table + suggested mapping + provenance strategy.
--    It holds CUSTOMER DATA (cell values), exactly like
--    IngestionJob.ParsedTableJson: bank-scoped under RLS and deleted by the
--    retention purge (RetentionPurger, the bank's customer-data retention,
--    30 days by default) — never kept longer than the jobs it served.
--  * HitCount — how often the row was reused (also a metric, never audited).
--  * Toggle: the BANK setting ai.resultCache.enabled (default true).
--
-- ROW LEVEL SECURITY: the table carries BankId, so the afterMigrate callback
-- puts it under the tenant policy; RlsPolicyCoveragePgIT's inventory lists
-- 'airesultcache'. A bank never reads another bank's cached result, even for
-- byte-identical documents.
--
-- EXPAND/CONTRACT (docs/release/migration-policy.md): a new table only; the
-- previous release never reads it.
--
-- SCHEMA PARITY: the AiResultCacheEntry entity mirrors this file on the H2
-- test schema (ddl-auto: create).

CREATE TABLE IF NOT EXISTS AiResultCache (
    AiResultCacheId bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BankId          integer NOT NULL REFERENCES Bank (BankId),
    CacheKey        varchar(64) NOT NULL,
    PromptVersion   varchar(20) NOT NULL,
    Model           varchar(200) NOT NULL,
    ResultJson      text NOT NULL,
    CreatedAt       timestamptz NOT NULL,
    HitCount        integer NOT NULL DEFAULT 0,
    CONSTRAINT ux_airesultcache_bank_key UNIQUE (BankId, CacheKey)
);

-- The retention purge: one bank's rows older than the cutoff.
CREATE INDEX IF NOT EXISTS ix_airesultcache_bankid_createdat
    ON AiResultCache (BankId, CreatedAt);
