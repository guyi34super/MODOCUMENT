-- ws10 (maker/checker, gate B7, SEC-023): dual control on critical changes.
--
-- A critical change (user creation / role change / disable, template
-- update/delete) is no longer applied by the requester: it lands here as a
-- REQUESTED row (the MAKER side), and only a DIFFERENT user holding
-- change:approve can approve it (the CHECKER side) — approval executes the
-- registered applier in the same transaction and the row becomes APPLIED.
-- Self-approval is a hard 409, audited SELF_APPROVAL_BLOCKED (DENIED).
--
--  * PayloadJson — the full requested change as JSON. NEVER plaintext
--    secrets: USER_CREATE validates the temporary password against the
--    policy at SUBMIT time and stores only its Argon2id hash.
--  * Status — REQUESTED -> APPLIED (approve) / REJECTED (checker) /
--    CANCELLED (maker withdraws) / FAILED (an approved apply hit a changed
--    invariant, e.g. the last-admin guard). APPROVED is the transient
--    in-between; the synchronous apply never leaves it behind.
--  * Maker/CheckerUserId — who requested and who decided. The application
--    additionally asserts maker and checker belong to the same bank
--    (defense in depth: AppUsers is not under RLS).
--
-- ROW LEVEL SECURITY: the table carries BankId, so the
-- afterMigrate__rls_enforce.sql callback covers it automatically — a bank's
-- pending changes are invisible to every other tenant.
--
-- SCHEMA PARITY: the test profile builds its H2 schema from the JPA
-- entities (ddl-auto: create, Flyway disabled), so the PendingChange entity
-- must be kept in sync with this file by hand.

CREATE TABLE PendingChange (
    PendingChangeId  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BankId           integer NOT NULL REFERENCES Bank (BankId),
    ChangeType       varchar(40) NOT NULL,
    TargetEntityType varchar(40),
    TargetEntityId   varchar(64),
    PayloadJson      text NOT NULL,
    Status           varchar(20) NOT NULL,
    MakerUserId      integer NOT NULL REFERENCES AppUsers (AppUserId),
    MakerComment     varchar(500),
    CheckerUserId    integer REFERENCES AppUsers (AppUserId),
    CheckerComment   varchar(500),
    RequestedAt      timestamp(6) NOT NULL DEFAULT now(),
    DecidedAt        timestamp(6),
    AppliedAt        timestamp(6),
    CONSTRAINT ck_pendingchange_status CHECK (Status IN
        ('REQUESTED', 'APPROVED', 'REJECTED', 'CANCELLED', 'APPLIED', 'FAILED'))
);

CREATE INDEX IF NOT EXISTS ix_pendingchange_bankid_status ON PendingChange (BankId, Status);
CREATE INDEX IF NOT EXISTS ix_pendingchange_makeruserid ON PendingChange (MakerUserId);
