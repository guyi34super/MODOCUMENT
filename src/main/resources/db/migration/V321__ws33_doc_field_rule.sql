-- Document field rules (docs/doccreation/field-validation-contract.md §1, ws33):
-- the validation rules of a PDF template's fields, per blueprint (not per
-- version: a rule change never creates a template version). Rules on keys a
-- document's version does not have are skipped when it is validated.
--
--  * RuleType   — a DocRuleType name (REQUIRED, REGEX, EMAIL, LENGTH, RANGE,
--                 ALLOWED_VALUES, DATE_FORMAT, DATE_RANGE, EXPIRY_DATE,
--                 REQUIRED_IF, COMPARE). No CHECK: the enum lives in code.
--  * ConfigJson — the rule's settings (contract §3), at most 4 kB.
--  * Message    — the user's own error text (null = the default text).
--  * Severity   — ERROR blocks validation, WARNING is shown only.
--  * Origin     — MANUAL, IMPORTED (from a flow template field) or
--                 REGION_FLAG (the backfill below).
--  * SourceTemplateId / SourceFieldName — where an IMPORTED rule came from.
--
-- DocBlueprint.RulesRevision counts rule saves; a save must name the
-- revision it was based on (409 when stale), like overlay baseVersion.
--
-- BACKFILL: the Required flag of a region was stored but never enforced. It
-- becomes a REQUIRED rule (Origin REGION_FLAG) for the regions of each
-- blueprint's current version; from now on the rules are the single source
-- of truth (the Required column is still written, for rollback).
--
-- ROW LEVEL SECURITY: the table carries BankId, so the afterMigrate callback
-- puts it under the tenant policy (RlsPolicyCoveragePgIT lists it). The
-- backfill runs as the table owner, which RLS does not restrict.
--
-- EXPAND/CONTRACT (docs/release/migration-policy.md): a new table, a new
-- column with a default, and data inserts only.
--
-- SCHEMA PARITY: the DocFieldRule entity and DocBlueprint.rulesRevision
-- mirror this file on the H2 test schema (ddl-auto: create).

CREATE TABLE IF NOT EXISTS DocFieldRule (
    DocFieldRuleId   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BankId           integer NOT NULL REFERENCES Bank (BankId),
    BlueprintId      integer NOT NULL REFERENCES DocBlueprint (DocBlueprintId) ON DELETE CASCADE,
    RegionKey        varchar(64) NOT NULL,
    RuleType         varchar(32) NOT NULL,
    ConfigJson       text NOT NULL DEFAULT '{}',
    Message          varchar(300),
    Severity         varchar(8) NOT NULL DEFAULT 'ERROR',
    Origin           varchar(16) NOT NULL DEFAULT 'MANUAL',
    SourceTemplateId integer,
    SourceFieldName  varchar(255),
    SortOrder        integer NOT NULL DEFAULT 0,
    UpdatedAt        timestamp,
    CONSTRAINT ck_docfieldrule_severity CHECK (Severity IN ('ERROR', 'WARNING')),
    CONSTRAINT ck_docfieldrule_origin CHECK (Origin IN ('MANUAL', 'IMPORTED', 'REGION_FLAG'))
);

CREATE INDEX IF NOT EXISTS ix_docfieldrule_blueprint ON DocFieldRule (BlueprintId, RegionKey);
CREATE INDEX IF NOT EXISTS ix_docfieldrule_bankid ON DocFieldRule (BankId);

ALTER TABLE DocBlueprint ADD COLUMN IF NOT EXISTS RulesRevision integer NOT NULL DEFAULT 0;

INSERT INTO DocFieldRule (BankId, BlueprintId, RegionKey, RuleType, ConfigJson, Severity, Origin,
                          SortOrder, UpdatedAt)
SELECT r.BankId, r.BlueprintId, r.RegionKey, 'REQUIRED', '{}', 'ERROR', 'REGION_FLAG', 0, now()
FROM DocTemplateRegion r
JOIN DocBlueprint b ON b.DocBlueprintId = r.BlueprintId AND r.Version = b.CurrentVersion
WHERE r.Required = true
  AND NOT EXISTS (SELECT 1 FROM DocFieldRule f
                  WHERE f.BlueprintId = r.BlueprintId AND f.RegionKey = r.RegionKey
                    AND f.RuleType = 'REQUIRED');
