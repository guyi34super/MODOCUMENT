-- Multi-tenancy foundation (banks) and per-user security columns. Every user
-- now belongs to exactly one Bank; existing users are backfilled into a
-- deterministic default bank (BankId 1, Code 'DEFAULT') so the column can be
-- NOT NULL with a real foreign key. Role/TokenVersion/LastLoginAt back the
-- new RBAC + token-revocation architecture:
--  * Role        — coarse application role (ADMIN/APPROVER/READ_WRITE/
--                  READ_ONLY), carried in the JWT "roles" claim.
--  * TokenVersion— monotonically bumped on password change (and later on
--                  role change) so every outstanding access token whose
--                  token_ver claim is older is rejected.
--  * LastLoginAt — stamped on each successful login.
--
-- SCHEMA PARITY: the test profile builds its H2 schema from the JPA entities
-- (ddl-auto: create, Flyway disabled), so the Bank entity and the new AppUser
-- fields must be kept in sync with this file by hand.

CREATE TABLE Bank (
    BankId      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Code        varchar(40)  NOT NULL UNIQUE,
    Name        varchar(200) NOT NULL,
    CreatedDate timestamp(6) NOT NULL DEFAULT now()
);

-- Deterministic id 1 (see Bank.DEFAULT_BANK_ID in the code); move the identity
-- sequence past it so runtime inserts do not collide.
INSERT INTO Bank (BankId, Code, Name) VALUES (1, 'DEFAULT', 'Default Bank');
ALTER TABLE Bank ALTER COLUMN BankId RESTART WITH 2;

ALTER TABLE AppUsers ADD COLUMN BankId integer;
UPDATE AppUsers SET BankId = (SELECT BankId FROM Bank WHERE Code = 'DEFAULT');
ALTER TABLE AppUsers ALTER COLUMN BankId SET NOT NULL;
ALTER TABLE AppUsers
    ADD CONSTRAINT fk_appusers_bankid FOREIGN KEY (BankId) REFERENCES Bank (BankId);
CREATE INDEX IF NOT EXISTS ix_appusers_bankid ON AppUsers (BankId);

ALTER TABLE AppUsers ADD COLUMN Role varchar(20) NOT NULL DEFAULT 'READ_ONLY';
ALTER TABLE AppUsers ADD COLUMN TokenVersion integer NOT NULL DEFAULT 0;
ALTER TABLE AppUsers ADD COLUMN LastLoginAt timestamp(6);
