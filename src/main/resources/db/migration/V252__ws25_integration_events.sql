-- ws25 (phase 2, Bank Integration Hub — docs/phase2/contracts.md §7.2), SE4:
--
--  * IntegrationEvent — the bank's integration event stream (job validated /
--    failed, document released, extraction completed). Appended by
--    IntegrationEventLog.publish INSIDE the producer's transaction together
--    with the OutboundDelivery outbox rows of the subscribed EVENT flows, and
--    paged by SE2's GET /api/integration/v1/events (id > cursor, oldest
--    first). DataJson carries ids, counts and statuses only — never record
--    values. The id column follows the table naming convention
--    (IntegrationEventId; the contract's "Id bigserial" is the same identity).
--  * IngestionJob.Origin — who created a machine job: "flow:<id>/run:<id>"
--    or "api-client:<id>"; NULL for a person's upload (every existing row).
--
-- EXPAND/CONTRACT (docs/release/migration-policy.md): a new table and a
-- nullable column; the previous release never reads either and its INSERTs
-- leave Origin NULL.
--
-- SCHEMA PARITY: IntegrationEvent and IngestionJob entities mirror this file
-- on the H2 test schema (ddl-auto: create).

CREATE TABLE IF NOT EXISTS IntegrationEvent (
    IntegrationEventId bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BankId      integer NOT NULL REFERENCES Bank (BankId),
    Type        varchar(30) NOT NULL,
    EntityType  varchar(40) NOT NULL,
    EntityId    varchar(64) NOT NULL,
    DataJson    text NOT NULL DEFAULT '{}',
    OccurredAt  timestamptz NOT NULL,
    CONSTRAINT ck_integrationevent_type CHECK (Type IN ('INGESTION_VALIDATED',
        'INGESTION_FAILED', 'DOC_RELEASED', 'EXTRACTION_COMPLETED'))
);

-- The feed's paging scan: one bank, id after the cursor.
CREATE INDEX IF NOT EXISTS ix_integrationevent_bankid_id
    ON IntegrationEvent (BankId, IntegrationEventId);

ALTER TABLE IngestionJob ADD COLUMN IF NOT EXISTS Origin varchar(100);
