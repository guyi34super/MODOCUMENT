-- ws25 (phase 2, Bank Integration Hub — docs/phase2/contracts.md §7): the
-- integration core owned by SE4. Five tables, all carrying BankId, so the
-- afterMigrate callback puts every one of them under the tenant policy the
-- moment it exists (RlsPolicyCoveragePgIT's inventory lists them).
--
--  * IntegrationConnection — where a bank system is. ConfigJson holds the
--    NON-secret settings only (host, port, base URL, DB vendor/database/
--    schema, SFTP folder + pinned host-key fingerprint, timeouts). Secrets
--    are write-only: DIRECT mode stores the SecretVault ciphertext
--    (AES-256-GCM, per-bank key, SecretKeyVersion for rotation); AGENT mode
--    stores only SecretRef, the name of a secret held by the bank's agent.
--    AgentId is a plain nullable integer here — SE5's V261 adds the foreign
--    key to IntegrationAgent NOT VALID. AuthType: the OutboundAuthType names
--    (REST/WEBHOOK) plus PASSWORD (DATABASE/SFTP) and PRIVATE_KEY (SFTP).
--  * IntegrationFlow — what to receive or send, and when. Specs are stored
--    identifiers/relative paths only (never SQL); ApprovedVersion is the
--    flow Version a second admin approved for an OUTBOUND enable
--    (INTEGRATION_FLOW_ENABLE). CursorValue is the persisted watermark of an
--    incremental DATABASE pull; NextRunAt the next cron slot of a SCHEDULE
--    flow. TriggerType/CursorValue avoid the TRIGGER/CURSOR keywords.
--  * IntegrationRun — one execution. UNIQUE (FlowId, ScheduledFor) doubles as
--    the cross-task run lock: every ECS task's scheduler inserts the run of
--    a due slot and only the insert winner executes it. FlowId is null for a
--    connection test routed through an agent (Operation TEST).
--    StagedRecordsJson buffers the records an agent streams up until its
--    last page (capped by integration.maxRowsPerRun).
--  * IntegrationRunEvent — the run log shown on the run detail page (no
--    record values, no secrets).
--  * OutboundDelivery — the transactional outbox: producers insert it in the
--    SAME transaction as the state change (IntegrationEventLog.publish);
--    OutboundDispatcher sends with exponential backoff and dead-letters after
--    integration.webhookRetryAttempts. IdempotencyKey is set at the first
--    dispatch (run + batch hash) and reused by every retry.
--
-- EXPAND/CONTRACT (docs/release/migration-policy.md): new tables only; the
-- previous release never reads them.
--
-- SCHEMA PARITY: the test profile builds its H2 schema from the JPA entities
-- (ddl-auto: create, Flyway disabled), so the entities in
-- com.modocument.domain.entity mirror this file by hand (CHECKs via
-- @Check, defaults via @ColumnDefault). Foreign keys are PostgreSQL-only, as
-- for AlertLog/Announcement; the code deletes child rows explicitly.

CREATE TABLE IF NOT EXISTS IntegrationConnection (
    IntegrationConnectionId bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BankId           integer NOT NULL REFERENCES Bank (BankId),
    Name             varchar(100) NOT NULL,
    Type             varchar(20) NOT NULL,
    Mode             varchar(10) NOT NULL,
    AgentId          integer,
    ConfigJson       text NOT NULL DEFAULT '{}',
    AuthType         varchar(30) NOT NULL DEFAULT 'NONE',
    SecretCiphertext text,
    SecretKeyVersion integer,
    SecretRef        varchar(200),
    Status           varchar(20) NOT NULL DEFAULT 'UNTESTED',
    LastTestAt       timestamptz,
    LastTestResult   varchar(500),
    Version          integer NOT NULL DEFAULT 0,
    CreatedBy        integer NOT NULL,
    CreatedAt        timestamptz NOT NULL DEFAULT now(),
    UpdatedAt        timestamptz,
    CONSTRAINT uq_integrationconnection_bankid_name UNIQUE (BankId, Name),
    CONSTRAINT ck_integrationconnection_type
        CHECK (Type IN ('REST_API', 'DATABASE', 'SFTP', 'WEBHOOK')),
    CONSTRAINT ck_integrationconnection_mode CHECK (Mode IN ('DIRECT', 'AGENT')),
    CONSTRAINT ck_integrationconnection_authtype CHECK (AuthType IN ('NONE', 'BASIC', 'BEARER',
        'API_KEY_HEADER', 'OAUTH2_CLIENT_CREDENTIALS', 'MTLS', 'HMAC_SIGNATURE', 'PASSWORD',
        'PRIVATE_KEY')),
    CONSTRAINT ck_integrationconnection_status
        CHECK (Status IN ('UNTESTED', 'OK', 'FAILED', 'DISABLED')),
    CONSTRAINT ck_integrationconnection_agent
        CHECK ((Mode = 'AGENT' AND AgentId IS NOT NULL) OR (Mode = 'DIRECT' AND AgentId IS NULL))
);

CREATE TABLE IF NOT EXISTS IntegrationFlow (
    IntegrationFlowId bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BankId           integer NOT NULL REFERENCES Bank (BankId),
    Name             varchar(100) NOT NULL,
    ConnectionId     bigint NOT NULL REFERENCES IntegrationConnection (IntegrationConnectionId),
    TemplateId       integer,
    Direction        varchar(10) NOT NULL,
    TriggerType      varchar(10) NOT NULL,
    CronExpression   varchar(120),
    Events           varchar(200),
    PayloadKinds     varchar(200) NOT NULL DEFAULT '',
    Format           varchar(10) NOT NULL DEFAULT 'JSON',
    SourceSpecJson   text,
    TargetSpecJson   text,
    FieldMappingJson text,
    MaskPii          boolean NOT NULL DEFAULT true,
    RowCap           integer,
    Enabled          boolean NOT NULL DEFAULT false,
    ApprovedVersion  integer,
    CursorValue      varchar(500),
    NextRunAt        timestamptz,
    Version          integer NOT NULL DEFAULT 0,
    CreatedBy        integer NOT NULL,
    CreatedAt        timestamptz NOT NULL DEFAULT now(),
    UpdatedAt        timestamptz,
    CONSTRAINT uq_integrationflow_bankid_name UNIQUE (BankId, Name),
    CONSTRAINT ck_integrationflow_direction CHECK (Direction IN ('INBOUND', 'OUTBOUND')),
    CONSTRAINT ck_integrationflow_triggertype
        CHECK (TriggerType IN ('MANUAL', 'SCHEDULE', 'EVENT')),
    CONSTRAINT ck_integrationflow_format CHECK (Format IN ('JSON', 'CSV', 'XLSX', 'PDF')),
    CONSTRAINT ck_integrationflow_rowcap CHECK (RowCap IS NULL OR RowCap > 0)
);

CREATE INDEX IF NOT EXISTS ix_integrationflow_connectionid ON IntegrationFlow (ConnectionId);
CREATE INDEX IF NOT EXISTS ix_integrationflow_bankid_enabled ON IntegrationFlow (BankId, Enabled);

CREATE TABLE IF NOT EXISTS IntegrationRun (
    IntegrationRunId  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BankId            integer NOT NULL REFERENCES Bank (BankId),
    FlowId            bigint REFERENCES IntegrationFlow (IntegrationFlowId),
    ConnectionId      bigint NOT NULL REFERENCES IntegrationConnection (IntegrationConnectionId),
    Operation         varchar(10) NOT NULL,
    TriggerType       varchar(10) NOT NULL,
    ScheduledFor      timestamptz NOT NULL,
    Status            varchar(20) NOT NULL,
    Attempt           integer NOT NULL DEFAULT 1,
    RecordsIn         integer NOT NULL DEFAULT 0,
    RecordsOut        integer NOT NULL DEFAULT 0,
    IngestionJobId    integer,
    Error             varchar(2000),
    CursorValue       varchar(500),
    StagedRecordsJson text,
    TriggeredBy       integer,
    CreatedAt         timestamptz NOT NULL DEFAULT now(),
    StartedAt         timestamptz,
    FinishedAt        timestamptz,
    CONSTRAINT uq_integrationrun_flowid_scheduledfor UNIQUE (FlowId, ScheduledFor),
    CONSTRAINT ck_integrationrun_operation CHECK (Operation IN ('READ', 'WRITE', 'TEST')),
    CONSTRAINT ck_integrationrun_triggertype
        CHECK (TriggerType IN ('MANUAL', 'SCHEDULE', 'EVENT')),
    CONSTRAINT ck_integrationrun_status CHECK (Status IN ('QUEUED', 'RUNNING', 'AWAITING_AGENT',
        'RUNNING_AGENT', 'SUCCEEDED', 'FAILED', 'CANCELLED'))
);

CREATE INDEX IF NOT EXISTS ix_integrationrun_bankid_status ON IntegrationRun (BankId, Status);
CREATE INDEX IF NOT EXISTS ix_integrationrun_bankid_createdat ON IntegrationRun (BankId, CreatedAt);
CREATE INDEX IF NOT EXISTS ix_integrationrun_connectionid ON IntegrationRun (ConnectionId);

CREATE TABLE IF NOT EXISTS IntegrationRunEvent (
    IntegrationRunEventId bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BankId     integer NOT NULL REFERENCES Bank (BankId),
    RunId      bigint NOT NULL REFERENCES IntegrationRun (IntegrationRunId),
    At         timestamptz NOT NULL,
    Level      varchar(10) NOT NULL,
    Message    varchar(1000) NOT NULL,
    CONSTRAINT ck_integrationrunevent_level CHECK (Level IN ('INFO', 'WARN', 'ERROR'))
);

CREATE INDEX IF NOT EXISTS ix_integrationrunevent_runid ON IntegrationRunEvent (RunId);

CREATE TABLE IF NOT EXISTS OutboundDelivery (
    OutboundDeliveryId bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BankId          integer NOT NULL REFERENCES Bank (BankId),
    FlowId          bigint NOT NULL REFERENCES IntegrationFlow (IntegrationFlowId),
    RunId           bigint REFERENCES IntegrationRun (IntegrationRunId),
    EventId         bigint,
    PayloadKind     varchar(30) NOT NULL,
    PayloadRef      varchar(200) NOT NULL,
    IdempotencyKey  varchar(100),
    Status          varchar(12) NOT NULL,
    Attempts        integer NOT NULL DEFAULT 0,
    NextAttemptAt   timestamptz,
    LastError       varchar(1000),
    RemoteReference varchar(300),
    CreatedAt       timestamptz NOT NULL DEFAULT now(),
    DeliveredAt     timestamptz,
    CONSTRAINT ck_outbounddelivery_status CHECK (Status IN ('PENDING', 'DELIVERED', 'DEAD')),
    CONSTRAINT ck_outbounddelivery_payloadkind CHECK (PayloadKind IN ('VALIDATED_RECORDS',
        'REJECTED_ROWS', 'JOB_STATUS', 'RELEASED_DOCUMENTS', 'EVENTS'))
);

-- The dispatcher's due scan (per bank, PENDING, oldest NextAttemptAt first).
CREATE INDEX IF NOT EXISTS ix_outbounddelivery_bankid_status_next
    ON OutboundDelivery (BankId, Status, NextAttemptAt);
CREATE INDEX IF NOT EXISTS ix_outbounddelivery_runid ON OutboundDelivery (RunId);
CREATE INDEX IF NOT EXISTS ix_outbounddelivery_flowid ON OutboundDelivery (FlowId);
