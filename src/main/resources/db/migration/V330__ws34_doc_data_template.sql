-- Document creation flow (docs/doccreation/data-templates-contract.md §1,
-- ws34): reusable validation templates ("data templates") — the fields a
-- document collects and their rules — chosen by PDF templates (blueprints)
-- after upload and mapped onto their fields (V331).
--
--  * DocDataTemplate.SourceTemplateId — the flow template it was copied
--    from (null when made from scratch); RulesRevision counts saves of its
--    fields and rules (a save names the revision it read; 409 when stale).
--  * DocDataField — FieldName unique per template; Kind as a region kind;
--    PropsJson the FieldProps JSON; SourceFieldName the flow field copied.
--  * DocDataFieldRule — the DocFieldRule columns (V321), keyed by the data
--    template and field name instead of a blueprint and region key.
--
-- ROW LEVEL SECURITY: every table carries BankId, so the afterMigrate
-- callback puts it under the tenant policy (RlsPolicyCoveragePgIT lists them).
-- EXPAND/CONTRACT (docs/release/migration-policy.md): new tables only.
-- SCHEMA PARITY: the entities mirror this file on H2 (ddl-auto: create).

CREATE TABLE IF NOT EXISTS DocDataTemplate (
    DocDataTemplateId integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BankId            integer NOT NULL REFERENCES Bank (BankId),
    OwnerUserId       integer NOT NULL,
    Name              varchar(200) NOT NULL,
    Description       varchar(1000),
    SourceTemplateId  integer,
    RulesRevision     integer NOT NULL DEFAULT 0,
    CreatedAt         timestamp NOT NULL,
    UpdatedAt         timestamp
);
CREATE INDEX IF NOT EXISTS ix_docdatatemplate_bankid ON DocDataTemplate (BankId);
CREATE INDEX IF NOT EXISTS ix_docdatatemplate_owner ON DocDataTemplate (OwnerUserId);

CREATE TABLE IF NOT EXISTS DocDataField (
    DocDataFieldId   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BankId           integer NOT NULL REFERENCES Bank (BankId),
    DataTemplateId   integer NOT NULL REFERENCES DocDataTemplate (DocDataTemplateId) ON DELETE CASCADE,
    FieldName        varchar(64) NOT NULL,
    Label            varchar(200) NOT NULL,
    Kind             varchar(16) NOT NULL DEFAULT 'TEXT',
    PiiKind          varchar(32),
    PropsJson        text,
    SourceFieldName  varchar(255),
    SortOrder        integer NOT NULL DEFAULT 0,
    CONSTRAINT ux_docdatafield_template_name UNIQUE (DataTemplateId, FieldName)
);
CREATE INDEX IF NOT EXISTS ix_docdatafield_bankid ON DocDataField (BankId);

CREATE TABLE IF NOT EXISTS DocDataFieldRule (
    DocDataFieldRuleId bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BankId             integer NOT NULL REFERENCES Bank (BankId),
    DataTemplateId     integer NOT NULL REFERENCES DocDataTemplate (DocDataTemplateId) ON DELETE CASCADE,
    FieldName          varchar(64) NOT NULL,
    RuleType           varchar(32) NOT NULL,
    ConfigJson         text NOT NULL DEFAULT '{}',
    Message            varchar(300),
    Severity           varchar(8) NOT NULL DEFAULT 'ERROR',
    Origin             varchar(16) NOT NULL DEFAULT 'MANUAL',
    SourceTemplateId   integer,
    SourceFieldName    varchar(255),
    SortOrder          integer NOT NULL DEFAULT 0,
    UpdatedAt          timestamp,
    CONSTRAINT ck_docdatafieldrule_severity CHECK (Severity IN ('ERROR', 'WARNING')),
    CONSTRAINT ck_docdatafieldrule_origin CHECK (Origin IN ('MANUAL', 'IMPORTED'))
);
CREATE INDEX IF NOT EXISTS ix_docdatafieldrule_template ON DocDataFieldRule (DataTemplateId, FieldName);
CREATE INDEX IF NOT EXISTS ix_docdatafieldrule_bankid ON DocDataFieldRule (BankId);
