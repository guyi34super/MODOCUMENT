-- ws06 (MFA, SEC-014/022): per-user TOTP enrolment and one-time recovery codes.
--
--  * UserMfa — at most one row per user. SecretCiphertext is the Base32 TOTP
--    secret encrypted with AES-256-GCM (key derived from MODOCUMENT_MFA_KEY;
--    random IV stored alongside the ciphertext) — the plaintext secret never
--    touches the database. EnabledAt NULL means "enrolled but not activated":
--    the secret was issued but the user has not yet proven possession with a
--    first TOTP code, so login does not demand a second factor yet.
--    LastUsedCounter is the RFC 6238 time-step counter of the last accepted
--    code; a same-or-older counter is rejected (replay prevention).
--  * RecoveryCode — ten one-time codes per enrolment, shown in plaintext
--    exactly once and stored only as password-encoder hashes (Argon2id).
--    UsedAt marks a code as burned.
--
-- No BankId on purpose (same reasoning as RefreshToken in V15): these rows
-- are keyed by the user and only reachable through the user's own
-- authenticated self-service endpoints, so the RLS afterMigrate callback
-- deliberately does not cover them.
--
-- SCHEMA PARITY: the test profile builds its H2 schema from the JPA entities
-- (ddl-auto: create, Flyway disabled), so the UserMfa and RecoveryCode
-- entities must be kept in sync with this file by hand.

CREATE TABLE UserMfa (
    UserId           integer PRIMARY KEY REFERENCES AppUsers (AppUserId),
    SecretCiphertext varchar(512) NOT NULL,
    EnabledAt        timestamp(6),
    LastUsedCounter  bigint,
    CreatedAt        timestamp(6) NOT NULL
);

CREATE TABLE RecoveryCode (
    RecoveryCodeId integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    UserId         integer NOT NULL REFERENCES AppUsers (AppUserId),
    CodeHash       varchar(255) NOT NULL,
    UsedAt         timestamp(6)
);

CREATE INDEX IF NOT EXISTS ix_recoverycode_userid ON RecoveryCode (UserId);
