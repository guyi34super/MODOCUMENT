-- ws20 (phase 2, settings framework): editable settings with guardrails.
--
-- BankSetting — one row per (bank, setting key) that differs from the
-- inherited value. The catalogue of keys, types and hard limits lives in
-- code (infrastructure/settings/SettingDefinitions); this table only holds
-- what an administrator changed:
--
--  * a CUSTOMER bank's row is that bank's override (ValueText); its
--    BankMinText/BankMaxText stay NULL;
--  * the PLATFORM bank's row (Bank code modocument.platform.bank-code) is
--    the platform layer: ValueText is the default every bank inherits, and
--    BankMinText/BankMaxText narrow what a bank may choose (inside the hard
--    limits in code, which nobody can override).
--
-- Values are canonical text ("12", "0.75", "true", "15m", "CODE_ONLY") so one
-- column serves every setting type; the application parses and re-checks
-- them on every load (an unparseable value is skipped with a WARN).
-- ValueText NULL means "inherit" — rows are never deleted, so Version only
-- ever grows (a new row starts at 1; the API hands it out as `version` and
-- checks it under a row lock on every write).
--
-- ROW LEVEL SECURITY: the table carries BankId, so the
-- afterMigrate__rls_enforce.sql callback covers it automatically — a bank
-- reads and writes only its own rows, and the WITH CHECK keeps every bank
-- admin out of the platform bank's rows (RlsPolicyCoveragePgIT lists
-- 'banksetting'). The settings cache reads all rows as SYSTEM (a registered
-- TenantContext.runAsSystem call site).
--
-- ConfigRevision — a single-row counter (Id = 1), bumped in the same
-- transaction as every settings write. Each application task polls it
-- (modocument.settings.poll-interval-ms, default 5 s) and reloads its
-- in-memory settings snapshot when it moved. No BankId (a counter, not
-- tenant data), so it is NOT under RLS; NonTenantTableInventoryPgIT pins it
-- in the inventory of tenant-less tables. The runtime role may read and bump
-- it, never delete it.
--
-- SCHEMA PARITY: the test profile builds its H2 schema from the JPA
-- entities (ddl-auto: create, Flyway disabled), so the BankSetting and
-- ConfigRevision entities must be kept in sync with this file by hand (the
-- Bank foreign key is PostgreSQL-only, like PendingChange's). On H2 the
-- ConfigRevision row is created at startup by SettingsCache.
--
-- Expand-only (docs/phase2/contracts.md, migration policy): two new tables,
-- one seed row, one REVOKE — nothing existing is altered.

CREATE TABLE BankSetting (
    BankSettingId   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BankId          integer NOT NULL REFERENCES Bank (BankId),
    SettingKey      varchar(100) NOT NULL,
    ValueText       varchar(2000),
    BankMinText     varchar(200),
    BankMaxText     varchar(200),
    Version         integer NOT NULL DEFAULT 0,
    UpdatedByUserId integer,
    UpdatedAt       timestamptz NOT NULL,
    CONSTRAINT uq_banksetting_bank_key UNIQUE (BankId, SettingKey)
);

CREATE TABLE ConfigRevision (
    Id        smallint PRIMARY KEY,
    Revision  bigint NOT NULL,
    UpdatedAt timestamptz NOT NULL,
    CONSTRAINT ck_configrevision_single_row CHECK (Id = 1)
);

INSERT INTO ConfigRevision (Id, Revision, UpdatedAt) VALUES (1, 0, now());

-- A counter the runtime only reads and bumps: losing the row would silently
-- stop cross-task propagation, so the app role cannot remove it.
REVOKE DELETE, TRUNCATE ON ConfigRevision FROM modocument_app;
