-- ws24 (phase 2, in-app notices — docs/phase2/contracts.md §3/§4): banners
-- the platform owner shows to bank users.
--
--  * Kind — INFO (general notice), MAINTENANCE (a planned window; never
--    dismissible in the SPA) or RELEASE (a new version is live; created by
--    DeployedVersionRecorder, or by a platform admin).
--  * Severity — INFO, WARNING or CRITICAL (banner colour).
--  * Title / Body — PLAIN TEXT. The API stores what the platform admin typed
--    and the SPA renders it as escaped text (React text nodes, never
--    dangerouslySetInnerHTML), so markup in a body shows up literally and
--    never executes. Title up to 200, body up to 2000 characters (checked by
--    the API; the column is text so the limit can move without a migration).
--  * AudienceBankCodes — NULL: every bank. Otherwise a comma-separated list
--    of Bank.Code values; only users of those banks see the banner.
--  * StartsAt / EndsAt — the display window (EndsAt after StartsAt).
--  * MaintenanceStartsAt / MaintenanceEndsAt — MAINTENANCE only: the outage
--    window shown in the banner, inside the display window.
--  * ReleaseVersion — RELEASE only: the X.Y.Z the banner links release notes
--    for ("What's new in X.Y.Z").
--  * Archived — DELETE /api/platform/announcements/{id} archives (the row
--    stays as evidence of what users were told).
--  * CreatedBy / UpdatedBy — AppUserId of the platform admin; NULL for the
--    system (the deployment recorder).
--
-- ROW LEVEL SECURITY: every row is owned by the PLATFORM bank (BankId = the
-- platform bank's id), so the afterMigrate callback puts the table under
-- the tenant policy and a customer tenant reading it directly sees NOTHING.
-- Banks receive announcements only through the API: AnnouncementCache reads
-- the platform bank's rows as that bank (TenantContext.runAs, a registered
-- call site) and serves each caller the active, audience-filtered subset
-- from memory. RlsPolicyCoveragePgIT's inventory lists 'announcement';
-- AnnouncementRlsPgIT proves the isolation.
--
-- EXPAND/CONTRACT (docs/release/migration-policy.md): a new table only; the
-- previous release never reads it.
--
-- SCHEMA PARITY: the test profile builds its H2 schema from the JPA entities
-- (ddl-auto: create, Flyway disabled), so the Announcement entity mirrors
-- this file by hand (the Bank foreign key and the partial index are
-- PostgreSQL-only, like AlertLog's).

CREATE TABLE IF NOT EXISTS Announcement (
    AnnouncementId      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BankId              integer NOT NULL REFERENCES Bank (BankId),
    Kind                varchar(20) NOT NULL,
    Severity            varchar(20) NOT NULL,
    Title               varchar(200) NOT NULL,
    Body                text NOT NULL,
    AudienceBankCodes   text,
    StartsAt            timestamptz NOT NULL,
    EndsAt              timestamptz NOT NULL,
    MaintenanceStartsAt timestamptz,
    MaintenanceEndsAt   timestamptz,
    ReleaseVersion      varchar(64),
    Archived            boolean NOT NULL DEFAULT false,
    CreatedBy           integer,
    CreatedAt           timestamptz NOT NULL,
    UpdatedBy           integer,
    UpdatedAt           timestamptz,
    CONSTRAINT ck_announcement_kind CHECK (Kind IN ('INFO', 'MAINTENANCE', 'RELEASE')),
    CONSTRAINT ck_announcement_severity CHECK (Severity IN ('INFO', 'WARNING', 'CRITICAL')),
    CONSTRAINT ck_announcement_window CHECK (EndsAt > StartsAt),
    CONSTRAINT ck_announcement_maintenance CHECK (
        (Kind = 'MAINTENANCE'
            AND MaintenanceStartsAt IS NOT NULL
            AND MaintenanceEndsAt IS NOT NULL
            AND MaintenanceEndsAt > MaintenanceStartsAt)
        OR (Kind <> 'MAINTENANCE'
            AND MaintenanceStartsAt IS NULL
            AND MaintenanceEndsAt IS NULL))
);

-- The cache loads the live rows (not archived, not yet ended) of the
-- platform bank; the platform console lists everything newest first.
CREATE INDEX IF NOT EXISTS ix_announcement_bankid_endsat
    ON Announcement (BankId, EndsAt) WHERE NOT Archived;
CREATE INDEX IF NOT EXISTS ix_announcement_bankid_createdat
    ON Announcement (BankId, CreatedAt);
