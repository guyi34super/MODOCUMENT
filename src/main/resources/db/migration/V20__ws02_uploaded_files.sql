-- ws02 (RBAC enforcement): per-upload ownership records.
--
-- Until now the shared uploads/ folder had no owner bookkeeping: any
-- authenticated user who knew (or guessed) a stored file name could point
-- /api/ingestion/jobs (JSON create) or /api/transform/transform at another
-- user's upload and have the pipeline read it. Every stored upload now gets a
-- row here (owner + bank stamped from the caller's JWT), and every endpoint
-- that accepts a fileName referencing an existing upload resolves the row and
-- requires OwnerUserId = current user (miss or mismatch answers 404, matching
-- the TemplateOwnership idiom).
--
-- CLEAN CUTOVER: files stored before this migration have no row, so their
-- stored names are treated as not-found from now on. Pre-launch there is no
-- upload worth preserving; re-uploading recreates the row. Nothing is
-- backfilled on purpose — a backfill could only guess at owners.
--
-- SCHEMA PARITY: the test profile builds its H2 schema from the JPA entities
-- (ddl-auto: create, Flyway disabled), so the UploadedFile entity must be
-- kept in sync with this file by hand.

CREATE TABLE UploadedFile (
    UploadedFileId integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    StoredName     varchar(255) NOT NULL UNIQUE,
    OriginalName   varchar(255),
    OwnerUserId    integer NOT NULL REFERENCES AppUsers (AppUserId),
    BankId         integer NOT NULL REFERENCES Bank (BankId),
    SizeBytes      bigint NOT NULL DEFAULT 0,
    UploadedAt     timestamp(6) NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_uploadedfile_owneruserid ON UploadedFile (OwnerUserId);
CREATE INDEX IF NOT EXISTS ix_uploadedfile_bankid ON UploadedFile (BankId);
