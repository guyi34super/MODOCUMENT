-- SQL backend for the extraction subsystem (extraction.store=sql, the new
-- default). Until now extraction sources/jobs/records lived either in memory
-- (lost on every restart) or in an optional MongoDB; these tables persist
-- them in the primary database, owned per user like every other root entity
-- (see V6__owner_columns.sql).
--
-- Design notes:
--  * ExtractionJob.SourceId carries no foreign key on purpose — parity with
--    the Mongo store, where deleting a source keeps its historical jobs.
--  * Counters live in their own table (ExtractionJobCounter) so concurrent
--    worker increments are single-row UPDATEs that a job save can't clobber.
--  * UNIQUE(SourceId, ContentHash) and UNIQUE(JobId, DedupKey) are the same
--    dedup guarantees the Mongo indexes enforce (source_hash / job_dedup).
--  * The in-flight task queue stays in memory: jobs interrupted by a restart
--    are marked FAILED at startup and can be re-run.
--
-- SCHEMA PARITY: the test profile builds its H2 schema from the JPA entities
-- in com.modocument.infrastructure.extraction.sql.entity (ddl-auto: create,
-- Flyway disabled), so those entities must be kept in sync with this file by
-- hand.

CREATE TABLE ExtractionSource (
    ExtractionSourceId bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OwnerUserId        integer NOT NULL REFERENCES AppUsers (AppUserId),
    Name               varchar(255) NOT NULL,
    Type               varchar(20)  NOT NULL,
    TermsAcknowledged  boolean      NOT NULL DEFAULT false,
    DataSpec           text,
    TemplateId         integer REFERENCES Template (TemplateId),
    WebConfigJson      text,
    ApiConfigJson      text,
    DbConfigJson       text,
    CreatedDate        timestamp(6),
    UpdatedDate        timestamp(6)
);
CREATE INDEX IF NOT EXISTS ix_extractionsource_owneruserid ON ExtractionSource (OwnerUserId);

CREATE TABLE ExtractionJob (
    ExtractionJobId bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OwnerUserId     integer NOT NULL REFERENCES AppUsers (AppUserId),
    SourceId        varchar(64),
    TemplateId      integer,
    DataSpec        text,
    Status          varchar(30) NOT NULL,
    Incremental     boolean     NOT NULL DEFAULT false,
    ErrorSummary    text,
    CreatedDate     timestamp(6),
    UpdatedDate     timestamp(6)
);
CREATE INDEX IF NOT EXISTS ix_extractionjob_owneruserid ON ExtractionJob (OwnerUserId);
CREATE INDEX IF NOT EXISTS ix_extractionjob_sourceid ON ExtractionJob (SourceId);
CREATE INDEX IF NOT EXISTS ix_extractionjob_status ON ExtractionJob (Status);

CREATE TABLE ExtractionJobCounter (
    JobId bigint      NOT NULL REFERENCES ExtractionJob (ExtractionJobId) ON DELETE CASCADE,
    Name  varchar(40) NOT NULL,
    CounterValue bigint NOT NULL DEFAULT 0,
    PRIMARY KEY (JobId, Name)
);

CREATE TABLE ExtractionRawRecord (
    ExtractionRawRecordId bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    JobId                 varchar(64) NOT NULL,
    SourceId              varchar(64) NOT NULL,
    Uri                   text,
    ContentType           varchar(255),
    Body                  text,
    Truncated             boolean NOT NULL DEFAULT false,
    ContentHash           varchar(64) NOT NULL,
    HttpStatus            integer,
    Etag                  varchar(512),
    LastModified          varchar(255),
    FetchedAt             timestamp(6),
    UNIQUE (SourceId, ContentHash)
);
CREATE INDEX IF NOT EXISTS ix_extractionrawrecord_jobid ON ExtractionRawRecord (JobId);

CREATE TABLE ExtractionProcessedRecord (
    ExtractionProcessedRecordId bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    JobId                       varchar(64) NOT NULL,
    RawRecordId                 varchar(64),
    FieldsJson                  text,
    DedupKey                    varchar(512) NOT NULL,
    ProcessedAt                 timestamp(6),
    UNIQUE (JobId, DedupKey)
);
CREATE INDEX IF NOT EXISTS ix_extractionprocessedrecord_jobid ON ExtractionProcessedRecord (JobId);

CREATE TABLE ExtractionAuditEvent (
    ExtractionAuditEventId bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    JobId                  varchar(64) NOT NULL,
    SourceId               varchar(64),
    Action                 varchar(30) NOT NULL,
    Uri                    text,
    Outcome                varchar(30),
    Detail                 text,
    EventTimestamp         timestamp(6)
);
CREATE INDEX IF NOT EXISTS ix_extractionauditevent_jobid ON ExtractionAuditEvent (JobId);

CREATE TABLE ExtractionConnectorState (
    SourceId         varchar(64) PRIMARY KEY,
    EtagsJson        text,
    LastModifiedJson text,
    LastCursor       text,
    LastWatermark    text,
    UpdatedDate      timestamp(6)
);
