-- ws18 (detection & export controls, gate items D1/D2; SEC-032): the alert
-- log — one row per security alert raised by the alert framework
-- (infrastructure/alerting). The audit trail (AuditEvent) stays the single
-- event source: an alert is DERIVED from one audit row (immediate rules —
-- AuditEventId names it) or from an aggregate over many (windowed rules —
-- AuditEventId names the newest row of the burst), and this table is the
-- delivery evidence that a person was told, and when:
--
--  * RuleName / Severity — which catalogue rule fired (modocument.alerts.rules).
--  * DedupeKey — SHA-256 hex of rule|bank|group key (actor, ip, entity):
--    a burst raises ONE alert per rule window. Hashed so the group key
--    (which may be an email or an IP) never sits in clear text here.
--  * EventCount — how many audit rows the alert summarises (1 for immediate).
--  * Summary — human-readable, PII-scrubbed (PiiPatterns) one-liner; never
--    carries audit value payloads.
--  * CreatedAt -> DeliveredAt — the detection-to-notification latency the
--    D1/D2 "< 5 minutes" evidence is read from (compare CreatedAt with the
--    triggering AuditEvent.OccurredAt for the detection half).
--  * Channel — the channels that ACCEPTED the alert so far (comma list,
--    e.g. "log,webhook"); Status — PENDING (a channel is still owed a
--    delivery; the minute sweep retries), SENT (every applicable channel
--    accepted), FAILED (gave up after the retry window; audited
--    ALERT_DELIVERY_FAILED).
--
-- ROW LEVEL SECURITY: the table carries BankId, so the
-- afterMigrate__rls_enforce.sql callback covers it automatically — a bank's
-- alerts are invisible to every other tenant (RlsPolicyCoveragePgIT's
-- inventory lists 'alertlog'). Writes happen under TenantContext.runAs(the
-- alert's bank), so the WITH CHECK passes; the cross-tenant windowed sweep
-- only READS AuditEvent as SYSTEM.
--
-- SCHEMA PARITY: the test profile builds its H2 schema from the JPA
-- entities (ddl-auto: create, Flyway disabled), so the AlertLog entity must
-- be kept in sync with this file by hand (the Bank foreign key is
-- PostgreSQL-only, exactly like PendingChange's).

CREATE TABLE AlertLog (
    AlertLogId   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BankId       integer NOT NULL REFERENCES Bank (BankId),
    RuleName     varchar(80) NOT NULL,
    Severity     varchar(10) NOT NULL,
    AuditEventId uuid,                       -- triggering / newest audit row; no FK (the trail has none)
    DedupeKey    varchar(64) NOT NULL,
    EventCount   integer NOT NULL DEFAULT 1,
    Summary      varchar(500) NOT NULL,
    CreatedAt    timestamptz NOT NULL,
    DeliveredAt  timestamptz,
    Channel      varchar(100),
    Status       varchar(10) NOT NULL,
    CONSTRAINT ck_alertlog_severity CHECK (Severity IN
        ('INFO', 'LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT ck_alertlog_status CHECK (Status IN ('PENDING', 'SENT', 'FAILED'))
);

-- Admin panel listing (newest first per bank), dedupe lookups and the
-- sweep's retry scan of PENDING deliveries.
CREATE INDEX IF NOT EXISTS ix_alertlog_bankid_createdat ON AlertLog (BankId, CreatedAt);
CREATE INDEX IF NOT EXISTS ix_alertlog_dedupekey_createdat ON AlertLog (DedupeKey, CreatedAt);
CREATE INDEX IF NOT EXISTS ix_alertlog_status_createdat ON AlertLog (Status, CreatedAt);
