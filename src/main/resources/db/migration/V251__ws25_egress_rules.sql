-- ws25 (phase 2, Bank Integration Hub — docs/phase2/contracts.md §7.2):
-- private-network destinations a bank's DIRECT connections may reach.
--
-- A bank's integration admin REQUESTS a destination (PENDING): either a
-- Host name / IP literal or a Cidr block, plus a Port and a Reason. It opens
-- nothing until two platform admins APPROVE it (maker/checker
-- EGRESS_RULE_APPROVE). The bank may REVOKE a rule at any time (direct).
-- BankEgressGuard consults the bank's APPROVED rules only for destinations
-- that resolve to private / loopback / link-local / VPN addresses; public
-- destinations pass under the global SSRF policy, and the cloud metadata
-- endpoints are refused whatever a rule says.
--
--  * Host — a DNS name or IP literal, lower-case, no scheme/port/path
--    (exact match); Cidr — e.g. 10.20.0.0/16 or fd12:3456::/48. Exactly one
--    of the two is set (ck_bankegressrule_target).
--  * Port — 1..65535 (ck_bankegressrule_port).
--  * RequestedByUserId — the bank user who asked; ApprovedByUserId — the
--    platform admin whose approval applied it (plain ints, like
--    PendingChange's maker/checker: AppUsers rows may be removed).
--
-- ROW LEVEL SECURITY: the table carries BankId, so the
-- afterMigrate__rls_enforce.sql callback covers it automatically
-- (RlsPolicyCoveragePgIT lists 'bankegressrule'). The platform console's
-- cross-bank listing and the approval read the rows as SYSTEM, and the
-- applier writes the approval under the rule's own bank — registered
-- TenantContext call sites.
--
-- EXPAND/CONTRACT (docs/release/migration-policy.md): a new table only; the
-- previous release never reads it.
--
-- SCHEMA PARITY: the test profile builds its H2 schema from the JPA entities
-- (ddl-auto: create, Flyway disabled), so the BankEgressRule entity mirrors
-- this file by hand (the Bank foreign key is PostgreSQL-only).

CREATE TABLE IF NOT EXISTS BankEgressRule (
    BankEgressRuleId  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BankId            integer NOT NULL REFERENCES Bank (BankId),
    Host              varchar(253),
    Cidr              varchar(64),
    Port              integer NOT NULL,
    Status            varchar(10) NOT NULL DEFAULT 'PENDING',
    Reason            varchar(500) NOT NULL,
    RequestedByUserId integer NOT NULL,
    ApprovedByUserId  integer,
    CreatedAt         timestamptz NOT NULL,
    ApprovedAt        timestamptz,
    CONSTRAINT ck_bankegressrule_target CHECK (
        (Host IS NOT NULL AND Cidr IS NULL) OR (Host IS NULL AND Cidr IS NOT NULL)),
    CONSTRAINT ck_bankegressrule_port CHECK (Port BETWEEN 1 AND 65535),
    CONSTRAINT ck_bankegressrule_status CHECK (Status IN ('PENDING', 'APPROVED', 'REVOKED'))
);

-- The guard loads one bank's APPROVED rules; the consoles list by bank and
-- status.
CREATE INDEX IF NOT EXISTS ix_bankegressrule_bankid_status
    ON BankEgressRule (BankId, Status);
