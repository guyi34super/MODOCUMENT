-- Document Creation engine: a company admin uploads their standard report
-- (.docx) as an immutable "blueprint"; the engine breaks it into sections by
-- headings, users fill each section with paragraphs and images (bulk image
-- upload auto-assigns by filename keywords), and generation reproduces the
-- original document exactly with the added content spliced into its sections.
--
-- Design notes:
--  * DocBlueprint.FileName points at the stored upload; the file is never
--    rewritten — DocBlueprintSection.AnchorParagraphIndex addresses body
--    elements of that exact file, and AnchorText double-checks the anchor
--    before every generation.
--  * DocBlueprint.CompanyId has no Company table yet (per-user ownership,
--    like every other root entity). NULL means "the owner is their own
--    company"; FlowKey records which DocumentCreationFlow strategy the
--    blueprint resolved to, DEFAULT unless a company-specific flow matched.
--  * DocInstance.BlueprintId is RESTRICT on purpose: deleting a blueprint
--    with documents built on it answers 409 instead of orphaning them.
--  * Invariant kept by DocInstanceUseCase in one transaction: an image asset
--    has AssignedSectionId set iff exactly one IMAGE content block references
--    it, and that block's SectionId equals AssignedSectionId. NULL = the
--    "Unsorted" tray.
--
-- SCHEMA PARITY: the test profile builds its H2 schema from the JPA entities
-- in com.modocument.doccreation.entity (ddl-auto: create, Flyway disabled),
-- so those entities must be kept in sync with this file by hand.

CREATE TABLE DocBlueprint (
    DocBlueprintId   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OwnerUserId      integer NOT NULL REFERENCES AppUsers (AppUserId),
    CompanyId        varchar(64),
    Name             varchar(255) NOT NULL,
    FileName         varchar(255) NOT NULL,
    OriginalFileName varchar(255),
    FlowKey          varchar(40) NOT NULL DEFAULT 'DEFAULT',
    CreatedDate      timestamp(6),
    UpdatedDate      timestamp(6)
);
CREATE INDEX ix_docblueprint_owneruserid ON DocBlueprint (OwnerUserId);

CREATE TABLE DocBlueprintSection (
    DocBlueprintSectionId integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BlueprintId           integer NOT NULL REFERENCES DocBlueprint (DocBlueprintId) ON DELETE CASCADE,
    OrderIndex            integer NOT NULL,
    Title                 varchar(500) NOT NULL,
    HeadingLevel          integer NOT NULL,
    AnchorParagraphIndex  integer NOT NULL,
    AnchorText            varchar(500),
    Keywords              varchar(1000)
);
CREATE INDEX ix_docblueprintsection_blueprintid ON DocBlueprintSection (BlueprintId);

CREATE TABLE DocInstance (
    DocInstanceId     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OwnerUserId       integer NOT NULL REFERENCES AppUsers (AppUserId),
    BlueprintId       integer NOT NULL REFERENCES DocBlueprint (DocBlueprintId),
    Title             varchar(255) NOT NULL,
    Status            varchar(20) NOT NULL DEFAULT 'DRAFT',
    LastGeneratedDocx varchar(255),
    LastGeneratedPdf  varchar(255),
    LastGeneratedDate timestamp(6),
    CreatedDate       timestamp(6),
    UpdatedDate       timestamp(6)
);
CREATE INDEX ix_docinstance_owneruserid ON DocInstance (OwnerUserId);
CREATE INDEX ix_docinstance_blueprintid ON DocInstance (BlueprintId);

CREATE TABLE DocImageAsset (
    DocImageAssetId   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    InstanceId        integer NOT NULL REFERENCES DocInstance (DocInstanceId) ON DELETE CASCADE,
    FileName          varchar(255) NOT NULL,
    OriginalFileName  varchar(255) NOT NULL,
    ContentType       varchar(100) NOT NULL,
    AssignedSectionId integer REFERENCES DocBlueprintSection (DocBlueprintSectionId),
    UploadedDate      timestamp(6)
);
CREATE INDEX ix_docimageasset_instanceid ON DocImageAsset (InstanceId);

CREATE TABLE DocContentBlock (
    DocContentBlockId integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    InstanceId        integer NOT NULL REFERENCES DocInstance (DocInstanceId) ON DELETE CASCADE,
    SectionId         integer NOT NULL REFERENCES DocBlueprintSection (DocBlueprintSectionId),
    BlockType         varchar(20) NOT NULL,
    OrderIndex        integer NOT NULL,
    TextContent       text,
    AssetId           integer REFERENCES DocImageAsset (DocImageAssetId) ON DELETE CASCADE,
    Caption           varchar(500)
);
CREATE INDEX ix_doccontentblock_instanceid ON DocContentBlock (InstanceId);
CREATE INDEX ix_doccontentblock_sectionid ON DocContentBlock (SectionId);
