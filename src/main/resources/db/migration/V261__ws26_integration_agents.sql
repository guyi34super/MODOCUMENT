-- ws26 (phase 2, bank integration hub — docs/phase2/contracts.md §7.2 and
-- docs/integration/agent.md): the on-prem Connector Agents of a bank.
--
--  * Status — PENDING_ENROLMENT (registered through maker/checker
--    AGENT_REGISTER, waiting for the agent's first call), ONLINE (enrolled;
--    the API shows OFFLINE when LastHeartbeatAt is older than the bank's
--    integration.agentHeartbeatTimeout setting — never stored that way by
--    the heartbeat itself), OFFLINE, REVOKED (terminal: every
--    /api/agent/v1 call of the agent is refused).
--  * Version / LastHeartbeatAt / LastHeartbeatJson — what the agent reported
--    on its last POST /api/agent/v1/heartbeat (its X.Y.Z, and per-connection
--    health [{connectionId, ok, message}], capped by the API).
--  * ApiClientId — the agent's machine identity (ApiClient, Kind AGENT,
--    scope AGENT_CONNECT), issued at enrolment by SE2's ApiClientIssuer.
--    A plain nullable int: ApiClient is V260 (another branch of the same
--    wave); the agent endpoints compare it with the caller's client id.
--  * EnrolmentTokenHash — SHA-256 (hex) of the secret part of the one-time
--    enrolment token. Only the hash is used to enrol (constant-time
--    compare), cleared at enrolment and on revocation; EnrolmentExpiresAt is
--    15 minutes after the approval.
--  * EnrolmentTokenCiphertext / EnrolmentTokenKeyVersion — the plaintext
--    token SEALED for the maker with the connector SecretVault (AES-256-GCM
--    under MODOCUMENT_CONNECTOR_KEY, per-bank data key). The maker reads it
--    once (GET …/agents/{id}/enrolment): EnrolmentReadAt is stamped and
--    both columns are cleared in the same transaction. Never readable after
--    the read, the expiry or the enrolment.
--  * CreatedByUserId — the MAKER of the AGENT_REGISTER change (the only
--    user who may read the token).
--
-- ROW LEVEL SECURITY: BankId, so the afterMigrate callback puts the table
-- under the tenant policy. The one pre-tenant read — POST
-- /api/agent/v1/enroll resolving the token's agent to its bank — is the
-- registered runAsSystem call site AgentEnrolmentService#enroll (see
-- TenantContext); the write that follows runs as that bank.
--
-- EXPAND/CONTRACT (docs/release/migration-policy.md): a new table and a
-- NOT VALID foreign key only; the previous release never reads either.
--
-- SCHEMA PARITY: the test profile builds its H2 schema from the JPA entities
-- (ddl-auto: create, Flyway disabled), so the IntegrationAgent entity mirrors
-- this file by hand (the Bank foreign key is PostgreSQL-only, like
-- Announcement's).

CREATE TABLE IF NOT EXISTS IntegrationAgent (
    IntegrationAgentId       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BankId                   integer NOT NULL REFERENCES Bank (BankId),
    Name                     varchar(100) NOT NULL,
    Status                   varchar(20) NOT NULL,
    Version                  varchar(64),
    LastHeartbeatAt          timestamptz,
    LastHeartbeatJson        text,
    ApiClientId              integer,
    EnrolmentTokenHash       varchar(64),
    EnrolmentTokenCiphertext text,
    EnrolmentTokenKeyVersion integer,
    EnrolmentExpiresAt       timestamptz,
    EnrolmentReadAt          timestamptz,
    EnrolledAt               timestamptz,
    CreatedByUserId          integer NOT NULL,
    CreatedAt                timestamptz NOT NULL,
    RevokedAt                timestamptz,
    RevokedByUserId          integer,
    CONSTRAINT ck_integrationagent_status
        CHECK (Status IN ('PENDING_ENROLMENT', 'ONLINE', 'OFFLINE', 'REVOKED'))
);

-- The admin list (per bank, by name) and the enrolment/agent-call lookup
-- (by id, which is the primary key).
CREATE INDEX IF NOT EXISTS ix_integrationagent_bankid_name
    ON IntegrationAgent (BankId, Name);

-- IntegrationConnection.AgentId → IntegrationAgent. IntegrationConnection is
-- created by V250__ws25_integration_core.sql, which lands on a parallel
-- branch of the same wave: this block is a no-op on a schema that does not
-- have the table (or the column) yet, so either branch migrates on its own,
-- and on the merged chain (V250 runs before V261) the key is added.
-- NOT VALID: existing rows are checked when a later release runs
-- VALIDATE CONSTRAINT (a contract step); new rows are checked from now on.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM information_schema.columns c
        WHERE c.table_schema = current_schema()
          AND c.table_name = 'integrationconnection'
          AND c.column_name = 'agentid'
    ) AND NOT EXISTS (
        SELECT 1
        FROM pg_catalog.pg_constraint k
        JOIN pg_catalog.pg_class t ON t.oid = k.conrelid
        JOIN pg_catalog.pg_namespace n ON n.oid = t.relnamespace
        WHERE n.nspname = current_schema()
          AND t.relname = 'integrationconnection'
          AND k.conname = 'fk_integrationconnection_agent'
    ) THEN
        ALTER TABLE IntegrationConnection
            ADD CONSTRAINT fk_integrationconnection_agent
            FOREIGN KEY (AgentId) REFERENCES IntegrationAgent (IntegrationAgentId) NOT VALID;
    END IF;
END
$$;
