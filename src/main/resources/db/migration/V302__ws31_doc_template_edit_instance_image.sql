-- Exact PDF templates (docs/doccreation/pdf-templates-contract.md §4, ws31).
--
--  * DocTemplateEdit — the changes that turn the original PDF into a
--    version's template PDF: REMOVE (data removal or a user erase),
--    REPLACE_TEXT, ADD_TEXT, ADD_IMAGE (ImageKey names an image uploaded for
--    the template). Source DATA_REMOVAL | USER. Boxes as in DocTemplateRegion.
--    The removed text itself is never stored (review only).
--  * DocInstance.ValuesJson — a document's values: a JSON object of region
--    key -> value. GeneratedPdfKey — the FileStore key of the last generated
--    PDF (the only output format).
--  * DocInstanceImage — the photos of a document: one row per uploaded
--    image (its file is the DocImageAsset row), placed in the image region
--    RegionKey, or in the tray when RegionKey is NULL.
--
-- ROW LEVEL SECURITY: both new tables carry BankId, so the afterMigrate
-- callback puts them under the tenant policy (RlsPolicyCoveragePgIT lists
-- them).
--
-- EXPAND/CONTRACT (docs/release/migration-policy.md): new tables and
-- nullable columns only.
--
-- SCHEMA PARITY: the entities mirror this file on the H2 test schema
-- (ddl-auto: create).

CREATE TABLE IF NOT EXISTS DocTemplateEdit (
    DocTemplateEditId integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BankId            integer NOT NULL REFERENCES Bank (BankId),
    BlueprintId       integer NOT NULL REFERENCES DocBlueprint (DocBlueprintId) ON DELETE CASCADE,
    Version           integer NOT NULL,
    EditId            varchar(64) NOT NULL,
    Kind              varchar(16) NOT NULL,
    Page              integer NOT NULL,
    X                 double precision NOT NULL,
    Y                 double precision NOT NULL,
    W                 double precision NOT NULL,
    H                 double precision NOT NULL,
    Text              text,
    FontName          varchar(64),
    FontSize          double precision,
    Color             varchar(7),
    ImageKey          varchar(128),
    Source            varchar(16) NOT NULL,
    CONSTRAINT ux_doctemplateedit_blueprint_version_edit UNIQUE (BlueprintId, Version, EditId)
);

CREATE INDEX IF NOT EXISTS ix_doctemplateedit_blueprint_version ON DocTemplateEdit (BlueprintId, Version);
CREATE INDEX IF NOT EXISTS ix_doctemplateedit_bankid ON DocTemplateEdit (BankId);

ALTER TABLE DocInstance ADD COLUMN IF NOT EXISTS ValuesJson text;
ALTER TABLE DocInstance ADD COLUMN IF NOT EXISTS GeneratedPdfKey varchar(512);

CREATE TABLE IF NOT EXISTS DocInstanceImage (
    DocInstanceImageId integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BankId             integer NOT NULL REFERENCES Bank (BankId),
    InstanceId         integer NOT NULL REFERENCES DocInstance (DocInstanceId) ON DELETE CASCADE,
    RegionKey          varchar(64),
    AssetId            integer NOT NULL REFERENCES DocImageAsset (DocImageAssetId) ON DELETE CASCADE,
    SortOrder          integer NOT NULL DEFAULT 0,
    OriginalName       varchar(255) NOT NULL
);

CREATE INDEX IF NOT EXISTS ix_docinstanceimage_instanceid ON DocInstanceImage (InstanceId);
CREATE INDEX IF NOT EXISTS ix_docinstanceimage_assetid ON DocInstanceImage (AssetId);
CREATE INDEX IF NOT EXISTS ix_docinstanceimage_bankid ON DocInstanceImage (BankId);
