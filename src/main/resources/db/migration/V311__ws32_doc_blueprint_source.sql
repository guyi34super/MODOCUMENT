-- Flow records in document creation (docs/doccreation/flow-records-contract.md
-- §1, ws32): the saved data sources of a PDF template (blueprint), per
-- blueprint (not per version).
--
--  * Role — PRIMARY (the record the user picks) or LINKED (found through a
--    shared key: KeyValue(LinkFieldThis) = normalised(primary[LinkFieldPrimary])).
--    LinkFieldPrimary / LinkFieldThis are null for the PRIMARY.
--  * MappingJson — region key -> template field name.
--  * One source per (blueprint, template); at most ONE PRIMARY per blueprint
--    (the partial unique index below; BlueprintSourceUseCase checks the same
--    rule first, so the H2 test schema, which has no partial indexes, behaves
--    alike).
--
-- ROW LEVEL SECURITY: the table carries BankId, so the afterMigrate callback
-- puts it under the tenant policy (RlsPolicyCoveragePgIT lists it).
--
-- EXPAND/CONTRACT (docs/release/migration-policy.md): a new table only.
--
-- SCHEMA PARITY: the DocBlueprintSource entity mirrors this file on the H2
-- test schema (ddl-auto: create).

CREATE TABLE IF NOT EXISTS DocBlueprintSource (
    DocBlueprintSourceId bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BankId               integer NOT NULL REFERENCES Bank (BankId),
    BlueprintId          integer NOT NULL REFERENCES DocBlueprint (DocBlueprintId) ON DELETE CASCADE,
    TemplateId           integer NOT NULL REFERENCES Template (TemplateId) ON DELETE CASCADE,
    Role                 varchar(16) NOT NULL,
    LinkFieldPrimary     varchar(200),
    LinkFieldThis        varchar(200),
    MappingJson          text NOT NULL,
    SortOrder            integer NOT NULL DEFAULT 0,
    UpdatedAt            timestamp,
    CONSTRAINT ux_docblueprintsource_blueprint_template UNIQUE (BlueprintId, TemplateId),
    CONSTRAINT ck_docblueprintsource_role CHECK (Role IN ('PRIMARY', 'LINKED'))
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_docblueprintsource_one_primary
    ON DocBlueprintSource (BlueprintId) WHERE Role = 'PRIMARY';
CREATE INDEX IF NOT EXISTS ix_docblueprintsource_bankid ON DocBlueprintSource (BankId);
CREATE INDEX IF NOT EXISTS ix_docblueprintsource_templateid ON DocBlueprintSource (TemplateId);
