-- Document-creation blueprint versions: a blueprint's section structure can be
-- edited (rename, re-level, add at a paragraph, delete, merge, re-run AI
-- sectioning). Every structural save writes a NEW version of the section list;
-- documents keep building on the version they were started from, new
-- documents use the latest. The stored source file never changes — sections
-- anchor into it by body-element index — so a version is only section rows.
--
--  * DocBlueprintVersion — one row per version: who made it, how its sections
--    were found (AI / HEURISTIC / MANUAL; NULL = unknown, pre-versioning) and
--    an optional note.
--  * DocBlueprint.CurrentVersion — the version new documents pin.
--  * DocBlueprintSection.Version — which version a section row belongs to.
--    Old versions' rows stay: content blocks and image assignments of older
--    documents reference them by id.
--  * DocInstance.BlueprintVersion — the version a document builds on.
--
-- ROW LEVEL SECURITY: DocBlueprintVersion carries BankId, so the afterMigrate
-- callback puts it under the tenant policy (RlsPolicyCoveragePgIT lists it).
--
-- EXPAND/CONTRACT (docs/release/migration-policy.md): a new table plus added
-- columns with defaults; the previous release keeps working (it never reads
-- them, and its inserts take the default version 1).
--
-- SCHEMA PARITY: the entities mirror this file on the H2 test schema
-- (ddl-auto: create).

CREATE TABLE IF NOT EXISTS DocBlueprintVersion (
    DocBlueprintVersionId integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BlueprintId           integer NOT NULL REFERENCES DocBlueprint (DocBlueprintId) ON DELETE CASCADE,
    BankId                integer NOT NULL REFERENCES Bank (BankId),
    Version               integer NOT NULL,
    SectionSource         varchar(16),
    Note                  varchar(500),
    CreatedByUserId       integer REFERENCES AppUsers (AppUserId),
    CreatedDate           timestamp NOT NULL,
    CONSTRAINT ux_docblueprintversion_blueprint_version UNIQUE (BlueprintId, Version)
);

CREATE INDEX IF NOT EXISTS ix_docblueprintversion_bankid ON DocBlueprintVersion (BankId);
CREATE INDEX IF NOT EXISTS ix_docblueprintversion_createdbyuserid ON DocBlueprintVersion (CreatedByUserId);

ALTER TABLE DocBlueprint ADD COLUMN IF NOT EXISTS CurrentVersion integer NOT NULL DEFAULT 1;
ALTER TABLE DocBlueprintSection ADD COLUMN IF NOT EXISTS Version integer NOT NULL DEFAULT 1;
ALTER TABLE DocInstance ADD COLUMN IF NOT EXISTS BlueprintVersion integer NOT NULL DEFAULT 1;

CREATE INDEX IF NOT EXISTS ix_docblueprintsection_blueprint_version_order
    ON DocBlueprintSection (BlueprintId, Version, OrderIndex);

-- Every existing blueprint becomes version 1 of itself.
INSERT INTO DocBlueprintVersion (BlueprintId, BankId, Version, SectionSource, Note, CreatedByUserId, CreatedDate)
SELECT b.DocBlueprintId, b.BankId, 1, NULL, NULL, b.OwnerUserId, COALESCE(b.CreatedDate, now())
FROM DocBlueprint b
WHERE NOT EXISTS (
    SELECT 1 FROM DocBlueprintVersion v WHERE v.BlueprintId = b.DocBlueprintId AND v.Version = 1
);
