-- Exact PDF templates (docs/doccreation/pdf-templates-contract.md §4, ws31):
-- the fill-in regions of a template version. A region is a box on one page
-- of the template PDF, in PDF points in the unrotated cropBox user space
-- (origin at the cropBox's lower-left corner; X/Y is the lower-left corner).
--
--  * RegionKey — the stable field key ([a-z0-9_]{1,64}), unique per version;
--    a document's values are keyed by it.
--  * Kind — TEXT | MULTILINE | DATE | NUMBER | CHECKBOX | IMAGE | SIGNATURE.
--  * FontName / FontSize (0 = auto) / Color (#RRGGBB) / Align / MaxLines —
--    how a value is drawn; taken from the removed or nearby text.
--  * AcroFieldName — the AcroForm field the region fills, if any.
--  * Source — ACROFORM | DETECTED | DATA_REMOVED | AI | MANUAL; Confidence 0..1.
--
-- The removed sample value of a WITH_DATA upload is NEVER stored here: it is
-- shown only while the template is under review (a draft file in the
-- FileStore, deleted when the template is confirmed).
--
-- ROW LEVEL SECURITY: the table carries BankId, so the afterMigrate callback
-- puts it under the tenant policy (RlsPolicyCoveragePgIT lists it).
--
-- EXPAND/CONTRACT (docs/release/migration-policy.md): a new table only.
--
-- SCHEMA PARITY: the DocTemplateRegion entity mirrors this file on the H2
-- test schema (ddl-auto: create).

CREATE TABLE IF NOT EXISTS DocTemplateRegion (
    DocTemplateRegionId integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BankId              integer NOT NULL REFERENCES Bank (BankId),
    BlueprintId         integer NOT NULL REFERENCES DocBlueprint (DocBlueprintId) ON DELETE CASCADE,
    Version             integer NOT NULL,
    RegionKey           varchar(64) NOT NULL,
    Label               varchar(200) NOT NULL,
    GroupName           varchar(120),
    Kind                varchar(16) NOT NULL,
    Page                integer NOT NULL,
    X                   double precision NOT NULL,
    Y                   double precision NOT NULL,
    W                   double precision NOT NULL,
    H                   double precision NOT NULL,
    FontName            varchar(64),
    FontSize            double precision NOT NULL DEFAULT 0,
    Color               varchar(7),
    Align               varchar(8) NOT NULL DEFAULT 'LEFT',
    MaxLines            integer NOT NULL DEFAULT 1,
    AcroFieldName       varchar(255),
    Required            boolean NOT NULL DEFAULT false,
    SortOrder           integer NOT NULL DEFAULT 0,
    Source              varchar(16) NOT NULL,
    Confidence          double precision NOT NULL DEFAULT 1,
    CONSTRAINT ux_doctemplateregion_blueprint_version_key UNIQUE (BlueprintId, Version, RegionKey)
);

CREATE INDEX IF NOT EXISTS ix_doctemplateregion_blueprint_version
    ON DocTemplateRegion (BlueprintId, Version);
CREATE INDEX IF NOT EXISTS ix_doctemplateregion_bankid ON DocTemplateRegion (BankId);
