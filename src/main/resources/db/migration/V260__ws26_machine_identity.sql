-- ws26 (phase 2, Bank Integration Hub — docs/phase2/contracts.md §7.2): the
-- machine identities a bank's own systems (and its on-prem Connector Agents)
-- use to call MoDocument's integration API.
--
-- ApiClient — one machine caller of ONE bank:
--  * Kind — SYSTEM (a bank system calling /api/integration/v1/**) or AGENT
--    (a Connector Agent calling /api/agent/v1/**, created only by
--    ApiClientIssuer during enrolment; AgentId names it, a plain int — the
--    IntegrationAgent table and its FK arrive with V261).
--  * AuthMethod — OAUTH2_CLIENT_CREDENTIALS | API_KEY | MTLS (chosen per
--    client by the bank admin; switchable off per bank by the platform
--    settings integration.auth.allow*).
--  * ClientId — the public identifier ("mdc_" + 24 random chars), unique.
--  * KeyPrefix — API_KEY only: the public half of "ApiKey <prefix>.<secret>"
--    the authenticator looks the client up by, unique.
--  * CertFingerprintSha256 / CertSubject — MTLS only: the SHA-256 of the
--    client certificate's DER (lower-case hex), unique across ALL banks
--    (the certificate is the lookup key before any tenant is known).
--  * Scopes — comma-separated Permission names (INTEGRATION_INGEST,
--    INTEGRATION_RESULTS, INTEGRATION_DOCS, INTEGRATION_EVENTS for SYSTEM;
--    AGENT_CONNECT for AGENT).
--  * AllowedCidrs — comma-separated IPv4/IPv6 CIDRs; NULL/empty = any address.
--  * ExpiresAt — NULL = no expiry; Status ACTIVE | REVOKED (revocation is
--    immediate and also bumps TokenVersion, which every issued client token
--    carries as token_ver).
--  * CreatedByUserId — the maker of the API_CLIENT_CREATE change; the jobs the
--    client creates are owned by this user (NULL for AGENT clients).
--
-- ApiClientSecret — the Argon2id hashes of a client's secrets (OAuth2
-- client_secret, or the secret half of an API key). ExpiresAt NULL = the
-- current secret; a rotation stamps the previous one with now + 24 h so both
-- work during the overlap.
--
-- ApiClientInitialSecret — the plaintext secret of a newly approved client,
-- SEALED with the SecretVault (per-bank key), readable ONCE by the maker
-- (RecipientUserId) within 24 h through GET
-- /api/admin/integrations/api-clients/{id}/initial-secret, then deleted.
--
-- IdempotencyKey — Idempotency-Key replay store of the integration API's
-- POSTs, per (bank, client, key): RequestHash is the SHA-256 of the request,
-- ResponseStatus/ResponseBody the stored answer (NULL while in flight).
-- Rows expire after 24 h and are purged opportunistically.
--
-- ROW LEVEL SECURITY: every table carries BankId, so the afterMigrate
-- callback covers it automatically. Client authentication happens BEFORE any
-- tenant is known, so ApiClientAuthenticator reads ApiClient/ApiClientSecret
-- by ClientId / KeyPrefix / CertFingerprintSha256 / id only, as SYSTEM, in
-- its own read-only transaction (a registered TenantContext.runAsSystem call
-- site; ApiClientAuthPgIT proves it on modocument_app).
--
-- EXPAND/CONTRACT (docs/release/migration-policy.md): four new tables only.
--
-- SCHEMA PARITY: the test profile builds its H2 schema from the JPA
-- entities (ddl-auto: create, Flyway disabled), so ApiClient,
-- ApiClientSecret, ApiClientInitialSecret and IdempotencyKey mirror this
-- file by hand (the Bank/ApiClient foreign keys are PostgreSQL-only).

CREATE TABLE ApiClient (
    ApiClientId           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BankId                integer NOT NULL REFERENCES Bank (BankId),
    Name                  varchar(100) NOT NULL,
    Kind                  varchar(10) NOT NULL,
    AuthMethod            varchar(30) NOT NULL,
    ClientId              varchar(64) NOT NULL,
    KeyPrefix             varchar(32),
    CertFingerprintSha256 varchar(64),
    CertSubject           varchar(500),
    Scopes                varchar(500) NOT NULL,
    AllowedCidrs          varchar(2000),
    ExpiresAt             timestamptz,
    Status                varchar(10) NOT NULL DEFAULT 'ACTIVE',
    TokenVersion          integer NOT NULL DEFAULT 0,
    LastUsedAt            timestamptz,
    CreatedByUserId       integer,
    CreatedAt             timestamptz NOT NULL,
    RevokedAt             timestamptz,
    RevokedByUserId       integer,
    AgentId               integer,
    CONSTRAINT uq_apiclient_clientid UNIQUE (ClientId),
    CONSTRAINT uq_apiclient_keyprefix UNIQUE (KeyPrefix),
    CONSTRAINT uq_apiclient_certfingerprint UNIQUE (CertFingerprintSha256),
    CONSTRAINT ck_apiclient_kind CHECK (Kind IN ('SYSTEM', 'AGENT')),
    CONSTRAINT ck_apiclient_authmethod
        CHECK (AuthMethod IN ('OAUTH2_CLIENT_CREDENTIALS', 'API_KEY', 'MTLS')),
    CONSTRAINT ck_apiclient_status CHECK (Status IN ('ACTIVE', 'REVOKED')),
    CONSTRAINT ck_apiclient_keyprefix
        CHECK ((AuthMethod = 'API_KEY') = (KeyPrefix IS NOT NULL)),
    CONSTRAINT ck_apiclient_certificate
        CHECK ((AuthMethod = 'MTLS') = (CertFingerprintSha256 IS NOT NULL))
);

CREATE INDEX ix_apiclient_bankid ON ApiClient (BankId);

CREATE TABLE ApiClientSecret (
    ApiClientSecretId integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BankId            integer NOT NULL REFERENCES Bank (BankId),
    ApiClientId       integer NOT NULL REFERENCES ApiClient (ApiClientId),
    SecretHash        varchar(255) NOT NULL,
    CreatedAt         timestamptz NOT NULL,
    ExpiresAt         timestamptz
);

CREATE INDEX ix_apiclientsecret_apiclientid ON ApiClientSecret (ApiClientId);

CREATE TABLE ApiClientInitialSecret (
    ApiClientId      integer PRIMARY KEY REFERENCES ApiClient (ApiClientId),
    BankId           integer NOT NULL REFERENCES Bank (BankId),
    RecipientUserId  integer NOT NULL,
    SecretCiphertext text NOT NULL,
    SecretKeyVersion integer NOT NULL,
    CreatedAt        timestamptz NOT NULL,
    ExpiresAt        timestamptz NOT NULL
);

CREATE INDEX ix_apiclientinitialsecret_bankid ON ApiClientInitialSecret (BankId);

CREATE TABLE IdempotencyKey (
    IdempotencyKeyId bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BankId           integer NOT NULL REFERENCES Bank (BankId),
    ApiClientId      integer NOT NULL REFERENCES ApiClient (ApiClientId),
    IdemKey          varchar(255) NOT NULL,
    RequestHash      varchar(64) NOT NULL,
    ResponseStatus   integer,
    ResponseBody     text,
    CreatedAt        timestamptz NOT NULL,
    ExpiresAt        timestamptz NOT NULL,
    CONSTRAINT uq_idempotencykey_bank_client_key UNIQUE (BankId, ApiClientId, IdemKey)
);

CREATE INDEX ix_idempotencykey_bankid_expiresat ON IdempotencyKey (BankId, ExpiresAt);
