-- Baseline PostgreSQL schema, matching the JPA entities in
-- com.modocument.domain.entity. Identifiers are intentionally unquoted so
-- PostgreSQL folds them to lowercase — the same names Hibernate emits at
-- runtime (PhysicalNamingStrategyStandardImpl, unquoted).

CREATE TABLE Template (
    TemplateId  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Name        varchar(255),
    Description varchar(255)
);

CREATE TABLE TemplateDataTypes (
    TemplateDataTypeId integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DataType           varchar(255)
);

CREATE TABLE ProcessStep (
    ProcessStepId integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Name          varchar(255),
    Description   varchar(255)
);

CREATE TABLE TemplateFields (
    TemplateFieldsId   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TemplateId         integer NOT NULL REFERENCES Template (TemplateId),
    FieldName          varchar(255),
    TemplateDataTypeId integer NOT NULL REFERENCES TemplateDataTypes (TemplateDataTypeId)
);

CREATE TABLE ValidationRules (
    TemplateId integer      NOT NULL REFERENCES Template (TemplateId),
    FieldName  varchar(255) NOT NULL,
    RuleType   smallint     NOT NULL,
    ConfigJson text         NOT NULL,
    PRIMARY KEY (TemplateId, FieldName, RuleType)
);

CREATE TABLE ImportHistory (
    ImportHistoryId integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ImportDate      timestamp(6),
    FileName        varchar(255),
    CompanyId       integer NOT NULL,
    TemplateId      integer NOT NULL REFERENCES Template (TemplateId)
);

CREATE TABLE ImportDetails (
    ImportDetailsId integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ImportHistoryId integer NOT NULL REFERENCES ImportHistory (ImportHistoryId),
    ProcessStepId   integer NOT NULL REFERENCES ProcessStep (ProcessStepId),
    RawJson         text
);

CREATE TABLE IngestionJob (
    IngestionJobId       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TemplateId           integer NOT NULL REFERENCES Template (TemplateId),
    FileName             varchar(255),
    ImportHistoryId      integer REFERENCES ImportHistory (ImportHistoryId),
    CurrentStep          varchar(20),
    Status               varchar(20),
    ErrorMessage         varchar(2000),
    ParsedTableJson      text,
    MappingJson          text,
    MappedRowsJson       text,
    ValidationResultJson text,
    ExportInfoJson       text,
    CreatedDate          timestamp(6),
    UpdatedDate          timestamp(6)
);

CREATE TABLE AppUsers (
    AppUserId    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Email        varchar(256) NOT NULL UNIQUE,
    PasswordHash varchar(100) NOT NULL,
    DisplayName  varchar(200),
    SettingsJson text,
    CreatedDate  timestamp(6),
    UpdatedDate  timestamp(6)
);
