#!/usr/bin/env python3
"""Generate docs/compliance/00-index.md from the crosswalk and the control data files."""
import re
from collections import Counter
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
PACK = ROOT / "docs" / "compliance"


def title(md):
    m = re.search(r"^#\s+(.+)$", md.read_text(encoding="utf-8"), re.M)
    return m.group(1).strip() if m else md.stem


def rel(p):
    return str(Path(p).relative_to("docs/compliance")) if str(p).startswith("docs/compliance") else p


def main():
    cw = yaml.safe_load((PACK / "crosswalk.yaml").read_text(encoding="utf-8"))
    data = {}
    for c in cw["controls"]:
        f = ROOT / c["data"]
        data[c["id"]] = yaml.safe_load(f.read_text(encoding="utf-8")) if f.exists() else {}

    out = ["# MoDocument technology-risk documentation pack — index", "",
           "This index maps every item in Bhavish's work checklist and in the three technology-risk workbooks "
           "(Security, Software Engineering, IT Infrastructure & Operations) to the document that answers it. "
           "Generated by `scripts/compliance/build_index.py`; completeness is checked by `scripts/compliance/check_pack.py`.",
           "", "Status values are those of the workbooks, re-verified against the repository on 2026-10-19. "
           "`TO CONFIRM` marks a company fact the repository cannot supply; `NOT IN REPO` marks evidence that only "
           "exists once the AWS environment is live.", ""]

    status = Counter(d.get("status") for d in data.values())
    tests = Counter((d.get("test") or {}).get("result") for d in data.values())
    ev = Counter((d.get("evidence") or {}).get("status") for d in data.values())
    out += ["## Summary", "", "| Measure | Count |", "|---|---|",
            f"| Checklist deliverables | {len(cw['tasks'])} |",
            f"| Controls | {len(cw['controls'])} |",
            f"| Questionnaire answers | {sum(1 for c in cw['controls'] if c['question'])} |"]
    out += [f"| Controls — {k} | {v} |" for k, v in sorted(status.items(), key=lambda x: str(x[0]))]
    out += [f"| Tests — {k} | {v} |" for k, v in sorted(tests.items(), key=lambda x: str(x[0]))]
    out += [f"| Evidence — {k} | {v} |" for k, v in sorted(ev.items(), key=lambda x: str(x[0]))]

    out += ["", "## Checklist deliverables (Bhavish)", "", "| Task | Deliverable | Document |", "|---|---|---|"]
    for t in cw["tasks"]:
        out.append(f"| {t['id']} | {t['deliverable']} | `{t['doc']}` |")

    for key, name in cw["workbooks"].items():
        out += ["", f"## {name}", "",
                "| Control | Name | Status | Questionnaire | Evidence | Test | Risk | Page |", "|---|---|---|---|---|---|---|---|"]
        for c in [c for c in cw["controls"] if c["workbook"] == key]:
            d = data[c["id"]]
            q = "answered" if (d.get("question") or {}).get("final_answer") else ("—" if not c["question"] else "MISSING")
            out.append(f"| {c['id']} | {c['name'].replace('|', '/')} | {d.get('status', 'MISSING')} | {q} | "
                       f"{c['id']}-E01 ({(d.get('evidence') or {}).get('status', '—')}) | "
                       f"{c['id']}-T01 ({(d.get('test') or {}).get('result', '—')}) | R-{c['id']} | `{c['page']}` |")

    out += ["", "## Policies, procedures and registers named by the workbooks", "",
            "| Control | Required by the workbook | Document |", "|---|---|---|"]
    for c in cw["controls"]:
        if c.get("policy_document"):
            out.append(f"| {c['id']} | {c['policy_document']} | `{data[c['id']].get('policy_document') or 'MISSING'}` |")

    pol = sorted((PACK / "policies").glob("*.md"))
    out += ["", "## All policies and procedures in this pack", "", "| Document | Title |", "|---|---|"]
    out += [f"| `{p.relative_to(ROOT)}` | {title(p)} |" for p in pol]
    evid = sorted(p for p in (PACK / "evidence").rglob("*") if p.is_file() and p.name != ".gitkeep")
    out += ["", "## Evidence captured for this pack", "", "| File | What it is |", "|---|---|"]
    out += [f"| `{p.relative_to(ROOT)}` | {title(p) if p.suffix == '.md' else p.suffix[1:].upper() + ' data'} |" for p in evid]
    (PACK / "00-index.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("wrote docs/compliance/00-index.md")


if __name__ == "__main__":
    main()
